const FILES = { O: "js/spirits.js", A: "js/app.js" };

module.exports = { RAW, FILES, nl, NLM, ROOT };

function main() {
  const write = process.argv.includes("--write");
  const buf = {};
  Object.keys(FILES).forEach((k) => { buf[k] = fs.readFileSync(path.join(ROOT, FILES[k]), "utf8"); });

  // 按 old 长度降序处理（长的先替，消除子串歧义）
  const pairs = RAW.map((r) => ({ id: r[0], f: r[1], expect: r[2], old: nl(r[3]), new: nl(r[4]) }))
    .sort((a, b) => b.old.length - a.old.length);

  let okCount = 0, dupCount = 0, miss = [], multi = [], occ = 0;
  const rows = [];
  pairs.forEach((p) => {
    const hay = buf[p.f];
    const idxs = [];
    let from = 0;
    for (;;) {
      const at = hay.indexOf(p.old, from);
      if (at < 0) break;
      idxs.push(at);
      from = at + p.old.length;
    }
    const c = idxs.length;
    occ += c;
    let status = "OK";
    if (p.expect === 0) { status = c === 0 ? "DUP" : "DUP!"; if (c === 0) dupCount++; else multi.push(p.id + "  DUP 但实得" + c); }
    else if (c === 0) { status = "MISS"; miss.push(p.id + "  " + p.old); }
    else if (c !== p.expect) { status = "MULTI"; multi.push(p.id + "  期望" + p.expect + " 实得" + c + "  " + p.old); okCount++; }
    else okCount++;
    if (c > 0) buf[p.f] = hay.split(p.old).join(p.new);
    rows.push([p.id, FILES[p.f], status, c]);
  });

  console.log("=== V168 替换模拟（" + (write ? "WRITE" : "DRY") + "）===");
  rows.forEach((r) => console.log(r[0].padEnd(7), r[1].padEnd(16), r[2].padEnd(6), "x" + r[3]));

  // 日文残留行删除
  const jp = "            { w: \"B\", t: \"(ないです。开玩笑的。)\" },\r\n";
  const jc = buf.O.split(jp).length - 1;
  console.log("\n日文残留行 命中数 =", jc, "(应为 1)");
  if (jc === 1) { buf.O = buf.O.split(jp).join(""); }

  console.log("\n--- 汇总 ---");
  console.log("pair 总数 =", pairs.length, " 完全命中 =", okCount, " 已知重复(已覆盖) =", dupCount, " 未命中 =", miss.length, " 计数异常 =", multi.length);
  console.log("文案替换总命中次数 =", occ, "（应为 189；含 你的光在抖。x2 / 安静发光的珠子 x2）");
  if (miss.length) { console.log("\n!! 未命中清单 !!"); miss.forEach((m) => console.log("  " + m)); }
  if (multi.length) { console.log("\n!! 计数异常（可能误伤）!!"); multi.forEach((m) => console.log("  " + m)); }

  if (write) {
    Object.keys(FILES).forEach((k) => fs.writeFileSync(path.join(ROOT, FILES[k]), buf[k], "utf8"));
    console.log("\n已写入：" + Object.keys(FILES).map((k) => FILES[k]).join(", "));
  }
}

if (require.main === module) main();
