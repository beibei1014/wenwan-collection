/* ---------------- 文本处理 ---------------- */
const TERM = /[。！？!?…]\s*$/;          // 句末（判定「」是否为句首）
// 判定：句首「」⇒ 对白；否则（引导语贴着引号，如「一个说」「慢慢地说了一句」「起先他不懂」）⇒ 转述语，留在旁白
function isDialoguePrev(prev) {
  const p = String(prev || "").trim();
  if (!p) return true;                       // 段首
  if (TERM.test(p)) return true;             // 上句已收尾
  return /[，、：]\s*$/.test(p);             // 「…。」X说，／他先开口，／顾时笙放下碗： ⇒ 同一句话的延续
}
