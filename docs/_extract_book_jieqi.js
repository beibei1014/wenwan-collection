/* ---------------- 文本处理 ---------------- */
const TERM = /[。！？!?…]\s*$/;          // 句末（判定「」是否为句首）
// 判定：句首「」⇒ 对白；否则（引导语贴着引号，如「一个说」「慢慢地说了一句」「起先他不懂」）⇒ 转述语，留在旁白
function isDialoguePrev(prev) {
  const p = String(prev || "").trim();
  if (!p) return true;                       // 段首
  if (TERM.test(p)) return true;             // 上句已收尾
  return /[，、：]\s*$/.test(p);             // 「…。」X说，／他先开口，／顾时笙放下碗： ⇒ 同一句话的延续
}
// ⛔ 按章取表：同一句台词在不同章可能是不同人
function speakerOf(ch, quote) {
  const list = SPEAKER[ch] || [];
  let hit = null, hitLen = -1;
  for (let i = 0; i < list.length; i++) {
    const p = list[i][0];
    if (String(quote).indexOf(p) === 0 && p.length > hitLen) { hit = list[i][1]; hitLen = p.length; }  // 最长前缀优先
  }
  return hit;
}

function run() {
  const raw = fs.readFileSync(MD, "utf8").replace(/\r/g, "");
  const lines = raw.split("\n");

  const chapters = [];
  let cur = null, para = [];

  const flushPara = () => {
    if (!cur) { para = []; return; }
    const text = para.join("").trim();
    para = [];
    if (!text) return;
    // 逐字扫描：区分「句首对白」与「句中转述语」
    let buf = "", i = 0, atParaStart = true;
    const pushNar = () => {
      const t = buf.trim();
      buf = "";
      if (t) cur.lines.push({ k: "n", t: t });
    };
    while (i < text.length) {
      const c = text[i];
      if (c === "「") {
        const b = text.indexOf("」", i + 1);
        if (b < 0) { buf += c; i++; continue; }
        const q = text.slice(i + 1, b);
        const prev = buf.trim();
        // ⛔ 相邻引号（如「苏栖盏」「萧景筹」「陆临崖」…）＝**枚举/并列**，一律留作旁白，
        //    ⛔ 绝不拆成一串对白（第 12 章萧景筹念名那一段正是此形）。
        const adjacentNext = text[b + 1] === "「";
        if (!adjacentNext && isDialoguePrev(prev)) {
          pushNar();
          const who = speakerOf(cur.no, q);
          cur.lines.push(who === ME ? { k: "me", t: q } : { k: "d", who: who || "", t: q });
        } else {
          buf += "「" + q + "」";                          // 转述语：连同书名号留在旁白里
        }
        i = b + 1;
        atParaStart = false;
        continue;
      }
      buf += c; i++;
    }
    pushNar();
    void atParaStart;
  };

  for (const rawL of lines) {
    const L = rawL.trim();
    // ⛔ 任何 `##` 标题都要收口：不只有章标题 —— 「## 章末」及其附录（A/B/C/D/E 表）
    //    若漏判，附录会整块被当成最后一章的旁白灌进正文。
    //    ⚠️「## 人称改造方案」（md 头部）也走 cur=null 分支 ⇒ ⛔ 绝不能被当成章。
    if (/^##\s+/.test(L)) {
      const mch = /^##\s*([一二三四五六七八九十]+)\s*·\s*(.+?)\s*$/.exec(L);
      if (mch && WANT.indexOf(mch[1]) >= 0) {
        cur = { no: mch[1], title: mch[2], lines: [], notes: [] };
        chapters.push(cur);
      } else cur = null;                       // 章末 / 附录 / 人称改造方案 ⇒ 停收
      para = [];
      continue;
    }
    if (!cur) continue;
    const msec = /^###\s*(.+?)\s*$/.exec(L);
    if (msec) { flushPara(); cur.lines.push({ k: "s", t: msec[1] }); continue; }
    if (/^〔/.test(L)) {
      flushPara();
      const inner = String(L).replace(/^〔/, "").replace(/〕\s*$/, "").replace(/^画面[：:]\s*/, "");
      cur.lines.push({ k: "sc", t: inner });
      continue;
    }
    if (/^\[/.test(L)) {
      flushPara();
      const m = /^\[(.+?)\]\s*(.*)$/.exec(L);
      if (m) cur.notes.push({ type: m[1], text: m[2] || "" });
      continue;
    }
    if (!L) { flushPara(); continue; }
    para.push(L);
  }
  flushPara();

  // 清理：① 只剩一个言语标签的残段（「你说，」「他说。」——说话人已由对白行承载，⛔ 别再当旁白重复一遍）
  //       ② 同一章内连续完全重复的行
  const TAG_ONLY = /^(你|他|她|那人|那一位|那一个|有人)?(又|也|终于|先)?(说|问|答|开口)[着了过]?[，。、]?$/;
  chapters.forEach((c) => {
    const out = [];
    c.lines.forEach((l) => {
      if (l.k === "n" && TAG_ONLY.test(String(l.t || "").trim())) return;
      const p = out[out.length - 1];
      if (p && p.k === l.k && p.t === l.t && p.who === l.who) return;
      out.push(l);
    });
    c.lines = out;
  });

  emit(chapters);
  report(chapters);
}

